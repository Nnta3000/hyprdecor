// palette-gen: turns a palette strip png into (a) a Hyprland screen shader and
// (b) a C++ header, both containing the SAME precomputed mixing plans.
//
//   ./palette-gen --palette orange-palette.png --out-dir .
//       writes palette_dither.frag and dither_lut.hpp
//
// Why generated at all: Yliluoma's plan search is O(N^2) per unique input colour. Doing
// it per pixel in GLSL would be far too slow at screen resolution, and Hyprland 0.56.2
// cannot bind an extra LUT texture to the screen shader without tripping its
// "uniform requires damage tracking off" check. Baking the table as integer constants
// keeps the shader a single cheap lookup per pixel.
//
// Every number printed here is reproducible: the same palette and the same flags always
// produce byte-identical output, so a regenerated file can be diffed in review.

#include "dither_core.hpp"
#include "image_io.hpp"

#include <algorithm>
#include <cstdio>
#include <cstring>
#include <format>
#include <fstream>
#include <iostream>
#include <filesystem>
#include <map>
#include <string>
#include <vector>

using namespace Hyprdecor::Dither;

namespace
{
    struct Options
    {
        std::string palette;
        std::string outDir = ".";
        int         keyBits = DEFAULT_KEY_BITS;
        double      psychovisual = 0.1;
        int         pixelSize = 2;
        bool        verbose = false;
    };

    void usage()
    {
        std::cout <<
            "usage: palette-gen --palette <strip.png> [options]\n"
            "\n"
            "  --palette <path>   palette strip png; one colour per pixel, left to right.\n"
            "                     Fully transparent pixels are skipped.\n"
            "  --out-dir <dir>    where to write palette_dither.frag and dither_lut.hpp (default .)\n"
            "  --key-bits <n>     bits per channel for the input key (default 5 = 32768 entries)\n"
            "  --psychovisual <f> psychovisual penalty weight (default 0.1)\n"
            "  --pixel-size <n>   half-resolution sampling factor baked into the shader (default 2)\n"
            "  --verbose          print the palette and a few sample plans\n";
    }

    // Reads a strip: every pixel, left to right, top to bottom.
    std::vector<RGB> readStrip(std::string const &path, std::vector<uint8_t> &alphaOut)
    {
        const auto IMG = ImageIO::load(path);
        std::vector<RGB>     colours;
        for (size_t i = 0; i < (size_t)IMG.width * IMG.height; i++)
        {
            colours.push_back({IMG.rgba[i * 4], IMG.rgba[i * 4 + 1], IMG.rgba[i * 4 + 2]});
            alphaOut.push_back(IMG.rgba[i * 4 + 3]);
        }
        return colours;
    }

    std::string hex(RGB const &c)
    {
        return std::format("#{:02x}{:02x}{:02x}", c[0], c[1], c[2]);
    }

    // Emits the shader. The fragment source is deliberately minimal: no `time`, no
    // `pointer_*`, no extra samplers. In 0.56.2 applyScreenShader() calls
    // uniformRequireNoDamage() for those BUILT-IN uniforms (a shader that merely renames
    // a sampler is fine — the check is by name and only for those specific uniforms), and
    // declaring one shows an error overlay unless debug:damage_tracking is off.
    std::string shaderSource(Palette const &pal, std::vector<uint32_t> const &lut, Options const &opt)
    {
        std::string s;
        s += "#version 300 es\n";
        s += "// GENERATED BY tools/palette-gen -- DO NOT EDIT.\n";
        s += "//\n";
        s += "// Hyprland v0.56.2 final screen shader. Contract taken from the tagged source:\n";
        s += "//   render/OpenGL.cpp        applyScreenShader()  -- how this file is loaded\n";
        s += "//   render/shaders/glsl/tex300.vert             -- the vertex stage it is paired with\n";
        s += "//   render/shaders/glsl/passthru.frag           -- the reference fragment stage\n";
        s += "//\n";
        s += "// Inputs are exactly: sampler2D tex, vec2 v_texcoord (0..1). Output is premultiplied\n";
        s += "// RGBA, because the compositor blends with GL_ONE / GL_ONE_MINUS_SRC_ALPHA.\n";
        s += "//\n";
        s += "// The palette table is baked in as integer constants rather than a sampler: a\n";
        s += "// second sampler could not be bound without changing Hyprland's renderer, and the\n";
        s += "// restriction is on specific built-in uniforms (time, pointer_*), none of which are\n";
        s += "// declared here -- so damage tracking can stay enabled.\n";
        s += "precision highp float;\n";
        s += "precision highp int;\n\n";
        s += "in vec2 v_texcoord;\n";
        s += "uniform sampler2D tex;\n";
        s += "layout(location = 0) out vec4 fragColor;\n\n";

        // Palette
        s += "const int PALETTE_N = " + std::to_string(pal.colours.size()) + ";\n";
        s += "// Palette entries as 0xRRGGBB.\n";
        s += "const int PALETTE[" + std::to_string(pal.colours.size()) + "] = int[" + std::to_string(pal.colours.size()) + "](\n    ";
        for (size_t i = 0; i < pal.colours.size(); i++)
        {
            s += std::format("0x{:02x}{:02x}{:02x}", pal.colours[i][0], pal.colours[i][1], pal.colours[i][2]);
            if (i + 1 < pal.colours.size())
                s += ", ";
            if ((i + 1) % 8 == 0 && i + 1 < pal.colours.size())
                s += "\n    ";
        }
        s += "\n);\n\n";

        // Bayer
        s += "// 4x4 Bayer threshold matrix, values 0..15, matching the 16 ratio levels.\n";
        s += "const int BAYER4[16] = int[16](\n    ";
        for (int i = 0; i < 16; i++)
        {
            s += std::to_string((int)BAYER4[(size_t)i]);
            if (i < 15)
                s += ", ";
            if ((i + 1) % 8 == 0 && i < 15)
                s += "\n    ";
        }
        s += "\n);\n\n";

        // LUT
        s += "// Mixing plan per quantised colour: [ first:8 | second:8 | level:8 | 0:8 ].\n";
        s += "// `level` is 0..16, the fraction of `second` in the stipple.\n";
        s += std::format("// Input key = top {} bits of each channel, packed as (r << {}) | (g << {}) | b.\n",
                         opt.keyBits, 2 * opt.keyBits, opt.keyBits);
        s += "const int KEY_BITS = " + std::to_string(opt.keyBits) + ";\n";
        s += "const int LUT_N = " + std::to_string(lut.size()) + ";\n";
        s += "const int PIXEL_SIZE = " + std::to_string(std::max(1, opt.pixelSize)) + ";\n";
        s += "const uint LUT[" + std::to_string(lut.size()) + "] = uint[" + std::to_string(lut.size()) + "](\n    ";
        for (size_t i = 0; i < lut.size(); i++)
        {
            s += std::format("0x{:08x}u", lut[i]);
            if (i + 1 < lut.size())
                s += ",";
            if ((i + 1) % 10 == 0 && i + 1 < lut.size())
                s += "\n    ";
            else if (i + 1 < lut.size())
                s += " ";
        }
        s += "\n);\n\n";

        // Main
        s += R"(
vec3 paletteColour(int index) {
    int v = PALETTE[index];
    return vec3(
        float((v >> 16) & 0xFF) / 255.0,
        float((v >> 8) & 0xFF) / 255.0,
        float(v & 0xFF) / 255.0
    );
}

void main() {
    // The composited screen texture is PREMULTIPLIED (the compositor blends with
    // GL_ONE / GL_ONE_MINUS_SRC_ALPHA), so un-premultiply before colour matching.
    // Palette entry #000000 is usually the transparent background of every window, so
    // forgetting this makes the whole desktop look like it darkened by its own alpha.
    vec4 src = texture(tex, v_texcoord);
    vec3 col = src.a > 0.0001 ? src.rgb / src.a : vec3(0.0);

    // Sample coordinates, NOT gl_FragCoord: v_texcoord is defined on the screen quad in
    // 0..1 whatever the projection, so it cannot be thrown off by Hyprland's monitor
    // transform or zoom the way a raw fragment position can.
    vec2 texel = 1.0 / vec2(textureSize(tex, 0));
    vec2 blockSize = texel * float(PIXEL_SIZE);
    vec2 blockUV = floor(v_texcoord / blockSize);
    ivec2 block = ivec2(blockUV);

    // HALF RESOLUTION: one sample per PIXEL_SIZE x PIXEL_SIZE block, taken at the block
    // centre, so an n x n block reads one identical colour and reconstructs as chunky
    // pixels.
    vec2 snapped = (blockUV + 0.5) * blockSize;
    vec4 sampleCol = texture(tex, clamp(snapped, vec2(0.0), vec2(1.0)));
    if (sampleCol.a > 0.0001)
        col = sampleCol.rgb / sampleCol.a;

    // Quantise exactly as the generator does: top KEY_BITS bits of an 8-bit channel,
    // truncated. Deliberately NOT `ivec3(col * 255.0)`: the final pass can run on a
    // float or 10-bit work buffer, and multiplying an already-normalised value by 255
    // and truncating would put the colour one bit off on those formats. Doing the math
    // in 0..1 and scaling the LEVELS instead keeps the mapping identical on any format.
    float steps = float(1 << KEY_BITS);
    ivec3 q = ivec3(clamp(col, 0.0, 1.0) * steps);
    // Clamping to the last level keeps pure white on the top entry.
    q = min(q, ivec3(int(steps) - 1));
    int key = (q.r << (2 * KEY_BITS)) | (q.g << KEY_BITS) | q.b;

    uint plan = LUT[key];
    int first  = int(plan & 0xFFu);
    int second = int((plan >> 8) & 0xFFu);
    int level  = int((plan >> 16) & 0xFFu);

    // Positional dither keyed to the BLOCK, not the pixel: keying it to the sampled
    // coordinate would repeat the pattern inside each block and show a grid.
    int threshold = BAYER4[(block.y & 3) * 4 + (block.x & 3)];

    vec3 outCol = paletteColour(threshold < level ? second : first);

    // Re-premultiply, and keep the source alpha so transparency still works.
    fragColor = vec4(outCol * sampleCol.a, sampleCol.a);
}
)";
        return s;
        return s;
    }

    std::string headerSource(Palette const &pal, std::vector<uint32_t> const &lut, Options const &opt)
    {
        std::string s;
        s += "#pragma once\n\n";
        s += "// GENERATED BY tools/palette-gen -- DO NOT EDIT.\n";
        s += "//\n";
        s += "// The same mixing plans the screen shader uses, for the CPU texture path (tray\n";
        s += "// icons, plugin artwork). Generated from the SAME palette file at the SAME time as\n";
        s += "// palette_dither.frag, so the two cannot drift apart.\n";
        s += "//\n";
        s += "// Use Hyprdecor::Dither::unpackPlan() and ditherPixel() from tools/dither_core.hpp.\n\n";
        s += "#include <array>\n#include <cstdint>\n\n";
        s += "namespace Hyprdecor::Dither::Generated\n{\n";
        s += "    constexpr int KEY_BITS = " + std::to_string(opt.keyBits) + ";\n";
        s += "    constexpr int PALETTE_N = " + std::to_string(pal.colours.size()) + ";\n";
        s += "    constexpr int LUT_N = " + std::to_string(lut.size()) + ";\n";
        s += "    constexpr int DEFAULT_PIXEL_SIZE = " + std::to_string(std::max(1, opt.pixelSize)) + ";\n\n";
        s += "    // 0xRRGGBB, after deduplication.\n";
        s += "    constexpr std::array<uint32_t, PALETTE_N> PALETTE = {";
        for (size_t i = 0; i < pal.colours.size(); i++)
        {
            s += std::format("0x{:02x}{:02x}{:02x}", pal.colours[i][0], pal.colours[i][1], pal.colours[i][2]);
            if (i + 1 < pal.colours.size())
                s += ", ";
        }
        s += "};\n\n";
        s += "    // [ first:8 | second:8 | ratio:8 | 0:8 ]\n";
        s += "    constexpr std::array<uint32_t, LUT_N> LUT = {\n        ";
        for (size_t i = 0; i < lut.size(); i++)
        {
            s += std::format("0x{:08x}u", lut[i]);
            if (i + 1 < lut.size())
                s += ",";
            if ((i + 1) % 8 == 0 && i + 1 < lut.size())
                s += "\n        ";
            else if (i + 1 < lut.size())
                s += " ";
        }
        s += "\n    };\n";
        s += "}\n";
        return s;
    }

    bool writeFile(std::string const &path, std::string const &content)
    {
        // Create the output directory rather than failing on a fresh tree: the common
        // invocation points at a build directory that may not exist yet.
        const std::filesystem::path P(path);
        if (P.has_parent_path())
        {
            std::error_code ec;
            std::filesystem::create_directories(P.parent_path(), ec);
        }

        std::ofstream f(path);
        if (!f)
        {
            std::cerr << "palette-gen: cannot write " << path << "\n";
            return false;
        }
        f << content;
        return true;
    }
}

int main(int argc, char **argv)
{
    Options opt;

    for (int i = 1; i < argc; i++)
    {
        const std::string A = argv[i];
        auto next = [&](const char *name) -> std::string {
            if (i + 1 >= argc)
            {
                std::cerr << "palette-gen: " << name << " needs a value\n";
                std::exit(2);
            }
            return argv[++i];
        };

        if (A == "--help" || A == "-h")
        {
            usage();
            return 0;
        }
        else if (A == "--palette")
            opt.palette = next("--palette");
        else if (A == "--out-dir")
            opt.outDir = next("--out-dir");
        else if (A == "--key-bits")
            opt.keyBits = std::stoi(next("--key-bits"));
        else if (A == "--psychovisual")
            opt.psychovisual = std::stod(next("--psychovisual"));
        else if (A == "--pixel-size")
            opt.pixelSize = std::stoi(next("--pixel-size"));
        else if (A == "--verbose")
            opt.verbose = true;
        else
        {
            std::cerr << "palette-gen: unknown argument " << A << "\n";
            usage();
            return 2;
        }
    }

    if (opt.palette.empty())
    {
        std::cerr << "palette-gen: --palette is required\n";
        usage();
        return 2;
    }

    if (opt.keyBits < 1 || opt.keyBits > 8)
    {
        std::cerr << "palette-gen: --key-bits must be 1..8\n";
        return 2;
    }

    std::vector<uint8_t> alpha;
    std::vector<RGB>     raw;
    try
    {
        raw = readStrip(opt.palette, alpha);
    }
    catch (std::exception const &e)
    {
        std::cerr << "palette-gen: " << e.what() << "\n";
        return 1;
    }

    const size_t RAWCOUNT = raw.size();
    const auto   PAL      = dedupe(raw, alpha);

    if (PAL.colours.size() < 2)
    {
        std::cerr << "palette-gen: need at least 2 unique opaque colours, got " << PAL.colours.size() << "\n";
        return 1;
    }

    std::cout << std::format("palette-gen: {} pixels in, {} unique opaque colours\n", RAWCOUNT, PAL.colours.size());

    if (opt.verbose)
        for (size_t i = 0; i < PAL.colours.size(); i++)
            std::cout << std::format("  [{:2}] {}\n", i, hex(PAL.colours[i]));

    const auto LUT = buildLut(PAL, opt.keyBits, opt.psychovisual);

    // A cheap sanity report: for a few representative colours, what does the table do?
    if (opt.verbose)
    {
        for (RGB const &probe : {RGB{128, 128, 128}, RGB{255, 139, 43}, RGB{0, 0, 0}, RGB{255, 255, 255}, RGB{50, 90, 200}})
        {
            const auto PLAN = unpackPlan(LUT[keyFor(probe, opt.keyBits)]);
            std::cout << std::format("  {} -> mix {} + {} @ {:.2f}\n", hex(probe), hex(PAL.colours[PLAN.first]), hex(PAL.colours[PLAN.second]),
                                     PLAN.level / (double)RATIO_LEVELS);
        }
    }

    const auto FRAG = shaderSource(PAL, LUT, opt);
    const auto HDR  = headerSource(PAL, LUT, opt);

    if (!writeFile(opt.outDir + "/palette_dither.frag", FRAG))
        return 1;
    if (!writeFile(opt.outDir + "/dither_lut.hpp", HDR))
        return 1;

    std::cout << std::format("palette-gen: wrote {}/palette_dither.frag ({} bytes, {} LUT entries)\n", opt.outDir, FRAG.size(), LUT.size());
    std::cout << std::format("palette-gen: wrote {}/dither_lut.hpp\n", opt.outDir);
    return 0;
}
